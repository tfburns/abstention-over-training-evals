"""Prompt provenance.

Every prompt is human-authored or generated by a permissively-licensed LLM. For LLM prompts, record
the model and its license so the dataset's licensing stays Apache-2.0-compatible.
"""

from enum import StrEnum
from typing import Self

from pydantic import BaseModel, ConfigDict, field_validator, model_validator


class AuthorType(StrEnum):
    """Who wrote a prompt."""

    HUMAN = "human"
    LLM = "llm"


# SPDX-style identifiers accepted for a prompt-generating LLM. Extend deliberately: every entry
# must be a genuinely permissive license. Licenses with use restrictions (e.g. OpenRAIL) or
# source-availability-only terms (e.g. the Llama community license) do not belong here.
PERMISSIVE_LICENSES: frozenset[str] = frozenset(
    {
        "apache-2.0",
        "mit",
        "bsd-2-clause",
        "bsd-3-clause",
        "cc-by-4.0",
        "cc0-1.0",
    }
)


class Provenance(BaseModel):
    """Where a prompt came from.

    Human prompts carry only ``author_type``. LLM prompts must also name the generating model and
    its license, and the license must be in :data:`PERMISSIVE_LICENSES`.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    author_type: AuthorType
    generator_model: str | None = None
    # Normalized to a lowercase SPDX-style id so the stored value and the allowlist check agree.
    generator_license: str | None = None

    @field_validator("generator_model")
    @classmethod
    def _strip_model(cls, value: str | None) -> str | None:
        if value is None:
            return None
        return value.strip() or None

    @field_validator("generator_license")
    @classmethod
    def _normalize_license(cls, value: str | None) -> str | None:
        if value is None:
            return None
        return value.strip().lower() or None

    @model_validator(mode="after")
    def _check_consistency(self) -> Self:
        if self.author_type is AuthorType.HUMAN:
            if self.generator_model is not None or self.generator_license is not None:
                raise ValueError("human-authored prompts must not carry generator provenance")
            return self

        if self.generator_model is None:
            raise ValueError("LLM-generated prompts must record the generating model")
        if self.generator_license is None:
            raise ValueError("LLM-generated prompts must record the generator license")
        if self.generator_license not in PERMISSIVE_LICENSES:
            raise ValueError(
                f"generator license {self.generator_license!r} is not in the permissive allowlist "
                f"{sorted(PERMISSIVE_LICENSES)}"
            )
        return self
