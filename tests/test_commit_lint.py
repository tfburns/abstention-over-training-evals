import pytest

from abstention_over_training_evals._commit_lint import MAX_HEADER_LENGTH, check


@pytest.mark.parametrize(
    "header",
    [
        "feat: add a rate-limit metric",
        "fix(judge): abstain on timeout",
        "docs: tidy the readme",
        "refactor!: drop the global override",
        "chore(ci): add the workflow",
        "perf(store): cache loaded prompts",
        "Merge pull request #3 from fork/branch",
        'Revert "feat: add a rate-limit metric"',
        "fixup! feat: add a rate-limit metric",
    ],
)
def test_accepts_conventional_and_autogenerated_headers(header):
    assert check(header) is None


@pytest.mark.parametrize(
    "header",
    [
        "",
        "add a thing",
        "feat add a thing",
        "Feat: capitalised type",
        "wip: not a real type",
        "feat:",
        "feat:no space after colon",
    ],
)
def test_rejects_invalid_headers(header):
    assert check(header) is not None


def test_rejects_overlong_header():
    assert check("feat: " + "x" * MAX_HEADER_LENGTH) is not None
